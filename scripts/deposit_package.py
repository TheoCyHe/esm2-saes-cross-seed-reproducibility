"""The Zenodo deposit package's generated half (amendment CT §CT18-D item 6,
§CT18-D2): the checksum list and the asset list, written from
`release/derived/MANIFEST.csv` after every file named there has been verified.

    python scripts/deposit_package.py [--bundle release/derived] [--out release/zenodo]

Writes `<out>/SHA256SUMS` (`sha256sum -c` format: every manifest row, then
MANIFEST.csv itself) and `<out>/ASSETS.md` (one row per asset: name, bytes,
sha256, producing commit, owning NoR rows). Refuses, writing nothing, if any
manifest row is absent from the bundle or hashes differently. The hand-written
half, `<out>/zenodo_metadata.json`, is not touched. Nothing is uploaded.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def build(bundle: Path, out: Path) -> dict:
    man = bundle / "MANIFEST.csv"
    rows = list(csv.DictReader(open(man, encoding="utf-8", newline="")))
    bad = []
    for r in rows:
        p = bundle / Path(r["path"]).name
        if not p.exists():
            bad.append(f"absent: {p.name}")
        elif sha256_file(p) != r["sha256"]:
            bad.append(f"hash differs: {p.name}")
    if bad:
        raise SystemExit("REFUSING: " + "; ".join(bad[:5]) + (f" (+{len(bad) - 5})" if len(bad) > 5 else ""))
    out.mkdir(parents=True, exist_ok=True)
    ms = sha256_file(man)
    lines = [f"{r['sha256']}  {Path(r['path']).name}" for r in rows] + [f"{ms}  MANIFEST.csv"]
    (out / "SHA256SUMS").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    total = sum((bundle / Path(r["path"]).name).stat().st_size for r in rows) + man.stat().st_size
    md = ["# Release assets: the derived bundle",
          "",
          "Generated by `scripts/deposit_package.py` from `release/derived/MANIFEST.csv`, after every row "
          "was verified against the files. Regenerate it whenever the manifest changes. "
          "`SHA256SUMS` beside this file lists the same hashes in `sha256sum -c` format.",
          "",
          f"**{len(rows) + 1} files, {total:,} bytes** (the manifest's {len(rows)} rows and `MANIFEST.csv`).",
          "",
          "| asset | bytes | sha256 | producing commit | owning NoR rows |",
          "|---|---:|---|---|---|"]
    for r in rows:
        p = bundle / Path(r["path"]).name
        md.append(f"| `{p.name}` | {p.stat().st_size:,} | `{r['sha256']}` | `{r['producing_commit'][:7]}` "
                  f"| {r['owning_nor_row'].replace('|', '/')} |")
    md.append(f"| `MANIFEST.csv` | {man.stat().st_size:,} | `{ms}` | — | the asset list itself |")
    (out / "ASSETS.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    return {"n_assets": len(rows) + 1, "bytes": total, "manifest_sha256": ms}


def md5_file(p: Path) -> str:
    h = hashlib.md5()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def write_tar(bundle: Path, rows: list[dict], dst: Path) -> None:
    """The bundle as one uncompressed tar (Zenodo allows 100 files per record):
    the manifest's files and MANIFEST.csv under `release_derived/`, sorted by
    name, every header fixed (mtime 0, uid/gid 0, no owner names, mode 0644),
    so the same files always give the same bytes."""
    import tarfile
    names = sorted([Path(r["path"]).name for r in rows] + ["MANIFEST.csv"])
    with tarfile.open(dst, "w", format=tarfile.USTAR_FORMAT) as tf:
        for n in names:
            ti = tf.gettarinfo(str(bundle / n), arcname=f"release_derived/{n}")
            ti.mtime, ti.uid, ti.gid, ti.uname, ti.gname, ti.mode = 0, 0, 0, "", "", 0o644
            with open(bundle / n, "rb") as f:
                tf.addfile(ti, f)


def build_upload(bundle: Path, decoders_manifest: Path, decoder_sums: Path, env_file: Path,
                 upload_dir: Path, out: Path) -> dict:
    """The Zenodo DATA record's upload set:
    `release_derived.tar`, `derived_MANIFEST.csv`, `decoders_MANIFEST.csv`,
    `reference_environment.yml` in `upload_dir`, plus the ten decoder files,
    which stay on Bouchet; their md5 and sha256 come from `decoder_sums` (the
    copy job's table), whose sha256 must equal the decoders' manifest. Writes
    `<out>/DATA_UPLOAD_CHECKSUMS.tsv`: file, bytes, md5, sha256, one row per
    file to upload. Refuses on any disagreement. The project record is not in this set: it is
    deposited on its own, with restricted files (section CT18-D17)."""
    rows = list(csv.DictReader(open(bundle / "MANIFEST.csv", encoding="utf-8", newline="")))
    build(bundle, out)                       # verifies every bundle file first
    upload_dir.mkdir(parents=True, exist_ok=True)
    write_tar(bundle, rows, upload_dir / "release_derived.tar")
    for src, name in ((bundle / "MANIFEST.csv", "derived_MANIFEST.csv"),
                      (decoders_manifest, "decoders_MANIFEST.csv"),
                      (env_file, "reference_environment.yml")):
        (upload_dir / name).write_bytes(src.read_bytes())
    small = ["release_derived.tar", "derived_MANIFEST.csv", "decoders_MANIFEST.csv", "reference_environment.yml"]
    dec = {r["asset"]: r for r in csv.DictReader(open(decoders_manifest, encoding="utf-8", newline=""))}
    sums = {r["asset"]: r for r in csv.DictReader(open(decoder_sums, encoding="utf-8", newline=""),
                                                    delimiter="\t")}
    if set(dec) != set(sums):
        raise SystemExit(f"REFUSING: decoder sums name {sorted(sums)} != manifest {sorted(dec)}")
    for n, r in dec.items():
        if sums[n]["sha256"] != r["sha256"] or int(sums[n]["bytes"]) != int(r["bytes"]):
            raise SystemExit(f"REFUSING: {n}: the copy's sha256 or size differs from the manifest")
    lines = ["file\tbytes\tmd5\tsha256"]
    for n in small:
        p = upload_dir / n
        lines.append(f"{n}\t{p.stat().st_size}\t{md5_file(p)}\t{sha256_file(p)}")
    for n in sorted(dec):
        lines.append(f"{n}\t{sums[n]['bytes']}\t{sums[n]['md5']}\t{sums[n]['sha256']}")
    (out / "DATA_UPLOAD_CHECKSUMS.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8",
                                                    newline="\n")
    return {"n_files": len(lines) - 1,
            "bytes": sum(int(l.split("\t")[1]) for l in lines[1:])}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bundle", type=Path, default=REPO / "release" / "derived")
    ap.add_argument("--out", type=Path, default=REPO / "release" / "zenodo")
    ap.add_argument("--upload-dir", type=Path, default=None,
                    help="also write the Zenodo data record's upload set here (gitignored)")
    ap.add_argument("--decoder-sums", type=Path, default=None,
                    help="the decoder copy job's table: asset, bytes, sha256, md5 (tab-separated)")
    a = ap.parse_args(argv)
    if a.upload_dir is not None:
        if a.decoder_sums is None:
            raise SystemExit("--upload-dir needs --decoder-sums")
        s = build_upload(a.bundle, REPO / "release" / "decoders" / "MANIFEST.csv", a.decoder_sums,
                         REPO / "env" / "reference_environment.yml", a.upload_dir, a.out)
        print(f"upload set: {s['n_files']} files, {s['bytes']:,} bytes; "
              f"checksums in {a.out / 'DATA_UPLOAD_CHECKSUMS.tsv'}")
        return 0
    s = build(a.bundle, a.out)
    print(f"{s['n_assets']} assets, {s['bytes']:,} bytes; MANIFEST.csv sha256 {s['manifest_sha256']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
